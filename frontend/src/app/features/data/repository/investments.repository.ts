/**
 * Text of an investment term: whole years from 12 months, months otherwise
 * (6 -> "6 meses", 12 -> "1 año", 24 -> "2 años")
 */
export function termLabel(months: number): { key: string; params: { count: number } } {
   if (months >= 12 && months % 12 === 0) {
      const years: number = months / 12;

      return {
         key: years === 1 ? INVESTMENTS_I18N_KEYS.TERM_YEAR : INVESTMENTS_I18N_KEYS.TERM_YEARS,
         params: { count: years },
      };
   }

   return { key: INVESTMENTS_I18N_KEYS.TERM_MONTHS, params: { count: months } };
}
